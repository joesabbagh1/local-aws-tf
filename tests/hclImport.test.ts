import { describe, expect, it } from 'vitest';
import { parseHclLiteral, parseHclStringMap, splitHclBody } from '../src/utils/hclBody';
import { parseTerraformHclToCanvas } from '../src/utils/hclImporter';
import { EXTRA_HCL_KEY } from '../src/utils/terraformCompiler';
import { IMPORT_FIXTURE_HCL } from './fixtures';

describe('splitHclBody', () => {
  it('finds top-level items through strings, interpolation, heredocs, comments and nesting', () => {
    const body = `
  name = "a { tricky } \\"quoted\\" \${var.x}" # trailing comment
  // line comment with = and {
  policy = <<-EOT
    { "Version": "2012-10-17" }
  EOT
  list = [
    "x",
    { y = 1 },
  ]
  /* block = comment { */
  lifecycle {
    ignore_changes = [tags]
  }
  dynamic "ingress" {
    for_each = var.ports
    content { from_port = ingress.value }
  }
  done = true
`;
    const items = splitHclBody(body);
    expect(items.map((i) => [i.key, i.kind])).toEqual([
      ['name', 'attribute'],
      ['policy', 'attribute'],
      ['list', 'attribute'],
      ['lifecycle', 'block'],
      ['dynamic', 'block'],
      ['done', 'attribute'],
    ]);
    expect(items[0].value).toBe('"a { tricky } \\"quoted\\" ${var.x}"');
    expect(items[1].text).toBe('policy = <<-EOT\n  { "Version": "2012-10-17" }\nEOT');
    expect(items[3].text).toBe('lifecycle {\n  ignore_changes = [tags]\n}');
  });

  it('reads literals and plain tag maps, and refuses expressions', () => {
    expect(parseHclLiteral('"python3.12"')).toBe('python3.12');
    expect(parseHclLiteral('512')).toBe(512);
    expect(parseHclLiteral('false')).toBe(false);
    expect(parseHclLiteral('var.memory')).toBeUndefined();
    expect(parseHclLiteral('"${var.env}-x"')).toBeUndefined();
    expect(parseHclStringMap('{\n  Team = "core"\n  "Cost-Center" = "42"\n}')).toEqual({ Team: 'core', 'Cost-Center': '42' });
    expect(parseHclStringMap('merge(local.tags, {})')).toBeUndefined();
  });
});

describe('parseTerraformHclToCanvas', () => {
  const result = parseTerraformHclToCanvas(IMPORT_FIXTURE_HCL);
  const fn = result.nodes.find((n) => n.data.serviceType === 'aws_lambda_function')!;
  const extra = String(fn.data.baseConfig[EXTRA_HCL_KEY]);

  it('maps literal values onto the form', () => {
    expect(fn.data.baseConfig.runtime).toBe('python3.12');
    expect(fn.data.baseConfig.timeout).toBe(15);
    expect(fn.data.tags).toMatchObject({ Team: 'payments' });
  });

  it('keeps arguments the form does not model as Extra HCL', () => {
    expect(extra).toMatch(/^publish\s+= true$/m);
    expect(extra).toContain('ephemeral_storage {\n  size = 1024\n}');
    expect(extra).toContain('lifecycle {\n  ignore_changes = [description]\n}');
    expect(extra).toMatch(/^kms_key_arn\s+= aws_kms_key\.payments_key\.arn$/m);
    expect(result.extraArgCount).toBe(6);
  });

  it('reports what it could not keep instead of dropping it silently', () => {
    expect(result.dropped).toEqual(
      expect.arrayContaining([
        { address: 'aws_lambda_function.payments-fn', key: 'role', reason: 'generated by LocalCloud' },
        { address: 'aws_lambda_function.payments-fn', key: 'memory_size', reason: 'not a literal value the form can hold' },
        { address: 'aws_sqs_queue.jobs', key: 'count', reason: 'not supported on the canvas' },
      ])
    );
    // aws_iam_role is a canvas service and becomes a node; the versioning helper has none
    expect(result.skippedResources).toEqual(['aws_s3_bucket_versioning.assets']);
  });

  it('follows renamed resources and warns about references the canvas lacks', () => {
    const queue = result.nodes.find((n) => n.data.serviceType === 'aws_sqs_queue')!;
    expect(String(queue.data.baseConfig[EXTRA_HCL_KEY])).toContain('aws_lambda_function.payments_fn.arn');
    expect(extra).toMatch(/^description\s+= "uses \$\{aws_sns_topic\.alerts\.arn\}"$/m);
    expect(result.warnings).toEqual([
      'payments-fn: Extra HCL refers to aws_sns_topic.alerts, which the canvas doesn\'t define',
    ]);
  });
});
